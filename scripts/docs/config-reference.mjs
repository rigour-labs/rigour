/**
 * docs/CONFIG_REFERENCE.md, generated: every rigour.yml setting from the schema (config-keys.mjs),
 * described in config-descriptions.json.
 *
 *   --write   regenerate the page (pnpm docs:config)
 *   --check   exit 1 when a setting has no description, a description has no setting, or the
 *             committed page is not what the schema renders (pnpm test runs it)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { configKeys } from './config-keys.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const DESCRIPTIONS = path.join(here, 'config-descriptions.json');
const PAGE = path.join(here, '..', '..', 'docs', 'CONFIG_REFERENCE.md');
const LONG = 60;

const cell = text => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const json = value => JSON.stringify(value);

/** The nearest described section a setting belongs to: its parent, or the parent's parent, up to the top level. */
function sectionOf(key, sections) {
    let parent = key.includes('.') ? key.slice(0, key.lastIndexOf('.')) : '';
    while (parent && !(parent in sections)) parent = parent.includes('.') ? parent.slice(0, parent.lastIndexOf('.')) : '';
    return parent;
}

/** Settings without a description, and descriptions without a setting. */
function mismatches(keys, descriptions) {
    const paths = new Set(keys.map(k => k.path));
    return {
        undescribed: [...paths].filter(p => !(p in descriptions.keys)),
        unknown: Object.keys(descriptions.keys).filter(p => !paths.has(p)),
    };
}

function render(keys = configKeys(), descriptions = JSON.parse(fs.readFileSync(DESCRIPTIONS, 'utf8'))) {
    const groups = new Map();
    for (const key of keys) {
        const section = sectionOf(key.path, descriptions.sections);
        if (!groups.has(section)) groups.set(section, []);
        groups.get(section).push(key);
    }
    const out = [
        '# Configuration reference',
        '',
        '<!-- Generated by scripts/docs/config-reference.mjs from the schema. Edit scripts/docs/config-descriptions.json, then run: node scripts/docs/config-reference.mjs --write -->',
        '',
        `Every setting \`rigour.yml\` accepts: ${keys.length} in all, generated from the schema Rigour validates the file with, so a default here is the default the code uses. Most teams change only a few of them; [Configuration](./CONFIGURATION.md) says which, and how settings combine.`,
        '',
        'A setting you leave out takes its default. A setting this page does not list is ignored.',
        '',
        '## Sections',
        '',
        ...[...groups.keys()].map(section => `- [${descriptions.sections[section]?.title ?? 'Top level'}](#${anchor(section, descriptions)})`),
    ];
    for (const [section, members] of groups) {
        const info = descriptions.sections[section] ?? { title: 'Top level', summary: '', blocks: '' };
        out.push('', `## ${info.title}`, '');
        if (section) out.push(`\`${section}\``, '');
        if (info.summary) out.push(info.summary, '');
        if (info.blocks) out.push(`**Blocks:** ${info.blocks}`, '');
        out.push('| Setting | Type | Default | What it does |', '| --- | --- | --- | --- |');
        const long = [];
        for (const key of members) {
            const name = section ? key.path.slice(section.length + 1) : key.path;
            let shown = key.default === undefined ? 'none' : `\`${cell(json(key.default))}\``;
            if (key.default !== undefined && json(key.default).length > LONG) {
                shown = 'see below';
                long.push(key);
            }
            out.push(`| \`${name}\` | ${cell(key.type)} | ${shown} | ${cell(descriptions.keys[key.path] ?? '')} |`);
        }
        for (const key of long) {
            out.push('', `<details><summary>Default of <code>${key.path}</code></summary>`, '', '```json', JSON.stringify(key.default, null, 2), '```', '', '</details>');
        }
    }
    return out.join('\n') + '\n';
}

/** GitHub's heading anchor for a section's title. */
function anchor(section, descriptions) {
    const title = descriptions.sections[section]?.title ?? 'Top level';
    return title.toLowerCase().replace(/[^\w\- ]/g, '').trim().replace(/ /g, '-');
}

const keys = configKeys();
const descriptions = JSON.parse(fs.readFileSync(DESCRIPTIONS, 'utf8'));
const { undescribed, unknown } = mismatches(keys, descriptions);
if (undescribed.length || unknown.length) {
    console.error(`Describe in scripts/docs/config-descriptions.json: ${undescribed.join(', ') || 'none'}\nRemove (no such setting): ${unknown.join(', ') || 'none'}`);
    process.exit(1);
}
const page = render(keys, descriptions);
if (process.argv.includes('--write')) fs.writeFileSync(PAGE, page);
else if (process.argv.includes('--check')) {
    // A Windows checkout has CRLF line endings; the page is the same page either way.
    if (fs.readFileSync(PAGE, 'utf8').replace(/\r\n/g, '\n') !== page) {
        console.error('docs/CONFIG_REFERENCE.md is out of date: run pnpm docs:config');
        process.exit(1);
    }
} else process.stdout.write(page);
