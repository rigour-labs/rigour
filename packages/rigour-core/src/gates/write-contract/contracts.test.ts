import { describe, expect, it } from 'vitest';
import { replayMigrations } from '../unindexed-reads/schema.js';
import { replayContracts } from './contracts.js';

const columns = (sql: string[], table = 'acme_orders') => Object.fromEntries(replayContracts(sql).tables.get(table)!.columns);

describe('replayContracts', () => {
    it('reads NOT NULL, defaults, serial, identity and generated columns', () => {
        const got = columns([`create table acme_orders (
            id bigserial primary key,
            ref bigint generated by default as identity,
            total numeric(10,2) not null,
            currency varchar(3) not null default 'usd'::character varying,
            label text default null,
            note text not null default null,
            cents bigint generated always as ((total * 100)::bigint) stored,
            tags text[] not null default '{}'
        );`]);
        expect(got.id).toMatchObject({ notNull: true, hasDefault: true });
        expect(got.ref).toMatchObject({ notNull: true, hasDefault: true });
        expect(got.total).toMatchObject({ notNull: true, hasDefault: false, type: 'numeric' });
        expect(got.currency).toMatchObject({ notNull: true, hasDefault: true, type: 'varchar' });
        expect(got.label).toMatchObject({ notNull: false, hasDefault: false });
        expect(got.note).toMatchObject({ notNull: true, hasDefault: false });
        expect(got.cents).toMatchObject({ generated: true });
        expect(got.tags.type).toBe('text[]');
    });

    it('reads a CHECK list in either form, and follows enum labels as ALTER TYPE changes them', () => {
        const contracts = replayContracts([
            `create type "Stage" as enum ('draft', 'live');
             create table acme_orders (
               state text not null,
               stage "Stage",
               constraint acme_orders_state_check check (((state)::text = any ((array['open'::character varying, 'closed'::character varying])::text[]))),
               check (priority in (1, 2, 3)),
               priority int
             );
             alter type "Stage" add value 'archived' after 'live';
             alter type "Stage" rename value 'draft' to 'pending';`,
        ]);
        const table = contracts.tables.get('acme_orders')!;
        expect(table.checks).toEqual([
            { name: 'acme_orders_state_check', column: 'state', values: [{ kind: 'string', text: 'open' }, { kind: 'string', text: 'closed' }] },
            { name: 'acme_orders_priority_check', column: 'priority', values: [1, 2, 3].map(n => ({ kind: 'number', text: String(n) })) },
        ]);
        expect(contracts.enums.get('Stage')).toEqual(['pending', 'live', 'archived']);
        expect(table.unknown).toBe(false);
    });

    it('applies ALTER TABLE actions in order and drops a constraint by its derived name', () => {
        const contracts = replayContracts([
            'create table acme_orders (id uuid primary key, state text check (state in (\'a\')), owner uuid references acme_users(id));',
            'alter table acme_orders drop constraint acme_orders_state_check, drop constraint acme_orders_owner_id_fkey;',
        ]);
        expect(contracts.tables.get('acme_orders')!.unknown).toBe(true); // no constraint has that second name
        const next = replayContracts([
            'create table acme_orders (id uuid primary key, state text check (state in (\'a\')), owner uuid references acme_users(id));',
            'alter table acme_orders drop constraint acme_orders_state_check, drop constraint acme_orders_owner_fkey, add column placed_at timestamptz;',
            'alter table acme_orders alter column placed_at set default now(), alter column placed_at set not null;',
            'alter table acme_orders rename to acme_purchases;',
        ]);
        const table = next.tables.get('acme_purchases')!;
        expect(table.unknown).toBe(false);
        expect(table.checks).toEqual([]);
        expect(table.columns.get('placed_at')).toMatchObject({ notNull: true, hasDefault: true });
    });

    it('marks a table unknown when something it does not model touches it', () => {
        const unknown = (sql: string) => replayContracts(['create table acme_orders (id uuid primary key, total int not null);', sql]).tables.get('acme_orders')!.unknown;
        expect(unknown('alter table acme_orders alter column total set statistics 100;')).toBe(false);
        expect(unknown('create trigger t after insert on acme_orders for each row execute function f();')).toBe(false);
        expect(unknown('create trigger t before insert or update on public.acme_orders for each row execute function f();')).toBe(true);
        expect(unknown('create rule r as on insert to acme_orders do instead nothing;')).toBe(true);
        expect(unknown('alter table acme_orders rename column total to amount;')).toBe(true);
        expect(unknown('cluster verbose acme_orders using acme_orders_pkey;')).toBe(false);
        expect(unknown('import foreign schema remote limit to (acme_orders) from server s into public;')).toBe(true);
    });
});

describe('a schema dump (supabase db dump, pg_dump)', () => {
    it('reads the table in full through the statements a dump adds around it', () => {
        const sql = `SET statement_timeout = 0;
SELECT pg_catalog.set_config('search_path', '', false);
CREATE TABLE IF NOT EXISTS "public"."acme_events" (
    "id" bigint NOT NULL,
    "kind" character varying(32) DEFAULT 'click'::character varying NOT NULL,
    "payload" "jsonb",
    CONSTRAINT "acme_events_kind_check" CHECK ((("kind")::"text" = ANY ((ARRAY['click'::character varying, 'view'::character varying])::"text"[])))
);
ALTER TABLE "public"."acme_events" OWNER TO "postgres";
CREATE SEQUENCE IF NOT EXISTS "public"."acme_events_id_seq" START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE "public"."acme_events_id_seq" OWNED BY "public"."acme_events"."id";
ALTER TABLE ONLY "public"."acme_events" ALTER COLUMN "id" SET DEFAULT "nextval"('"public"."acme_events_id_seq"'::"regclass");
ALTER TABLE ONLY "public"."acme_events" ADD CONSTRAINT "acme_events_pkey" PRIMARY KEY ("id");
ALTER TABLE "public"."acme_events" ENABLE ROW LEVEL SECURITY;
ALTER PUBLICATION "supabase_realtime" ADD TABLE ONLY "public"."acme_events";
GRANT ALL ON TABLE "public"."acme_events" TO "anon";`;
        const table = replayContracts([sql]).tables.get('acme_events')!;
        expect(table.unknown).toBe(false);
        expect(table.columns.get('id')).toMatchObject({ notNull: true, hasDefault: true });
        expect(table.checks[0]).toMatchObject({ column: 'kind', values: [{ kind: 'string', text: 'click' }, { kind: 'string', text: 'view' }] });
        expect(replayMigrations([sql]).get('acme_events')!.indexes.map(i => i.keys)).toEqual([['id']]);
    });
});

describe('replayMigrations: unique keys for ON CONFLICT', () => {
    it('records every key column of unique constraints and indexes, and drops a constraint by name', () => {
        const schema = replayMigrations([
            'create table acme_orders (id uuid primary key, org_id uuid, code text unique, constraint acme_orders_org_code unique (org_id, code));',
            'create unique index acme_orders_lower_code on acme_orders (lower(code));',
            'alter table acme_orders drop constraint acme_orders_code_key;',
        ]);
        expect(schema.get('acme_orders')!.indexes.map(i => [i.unique, i.keys])).toEqual([[true, ['id']], [true, ['org_id', 'code']], [true, null]]);
    });
});
